import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { test, expect, snap } from '../../helpers/scratch'
import { mockCreationMetadata } from '../../helpers/react-creation'
import { stubOpenDialog } from '../../helpers/tasks/importModpack'

test.use({ launcherOptions: { locale: 'es-ES' } })
for (const location of ['source', 'managed'] as const)
  test(`Prism partial base from ${location} is reviewed, revalidated and merged with loader patches natively`, async ({ launcher }) => {
    const page = launcher.main, errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await mockCreationMetadata(launcher)
    const source = join(launcher.gameDataPath, `partial-${location}`)
    async function put(path: string, data: string) { await mkdir(dirname(path), { recursive: true }); await writeFile(path, data) }
    await put(join(source, '.minecraft/saves/Sentinel/level.dat'), 'source-world')
    await put(join(source, 'instance.cfg'), `name=Partial ${location} QA\nJavaPath=personal.exe\nJvmArgs=-javaagent:personal.jar\nOverrideCommands=true\nPreLaunchCommand=never-run`)
    await put(join(source, 'mmc-pack.json'), JSON.stringify({ formatVersion: 1, components: [{ uid: 'net.minecraft', version: '1.7.10' }, { uid: 'net.minecraftforge', version: '10' }] }))
    await put(join(source, 'patches/net.minecraft.json'), JSON.stringify({ uid: 'net.minecraft', compatibleJavaMajors: [17, 21] }))
    await put(join(source, 'patches/net.minecraftforge.json'), JSON.stringify({ uid: 'net.minecraftforge', mainClass: 'custom.Main', '+jvmArgs': ['-Dcustom=true'], '+tweakers': ['custom.Tweaker'], libraries: [{ name: 'qa.partial:local:1', 'MMC-hint': 'local' }] }))
    await put(join(source, 'libraries/local-1.jar'), 'local-bootstrap')
    const client = 'synthetic-client-not-executed'
    await put(join(source, 'versions/1.7.10/1.7.10.jar'), client)
    const base = { id: '1.7.10', mainClass: 'vanilla.Main', minecraftArguments: '--username ${auth_player_name}', assets: 'legacy', libraries: [{ name: 'qa.base:library:1' }], downloads: { client: { url: 'https://example.com/client.jar', sha1: createHash('sha1').update(client).digest('hex'), size: client.length } }, javaVersion: { majorVersion: 8, component: 'jre-legacy' } }
    const baseFile = join(location === 'source' ? join(source, '.minecraft') : launcher.gameDataPath, 'versions/1.7.10/1.7.10.json')
    await put(baseFile, JSON.stringify(base))
    const originalClient = join(launcher.gameDataPath, 'versions/1.7.10/1.7.10.jar')
    await put(originalClient, 'keep-official')
    await page.getByTestId('nav-library').click()
    await page.getByTestId('library-create-instance').click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Importar modpack', exact: true }).click()
    await dialog.getByRole('button', { name: 'Carpeta existente', exact: true }).click()
    await page.getByLabel('Formato de la carpeta', { exact: true }).selectOption('prism')
    await stubOpenDialog(launcher, source)
    const review = dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true })
    await review.click()
    await expect(page.getByTestId('instance-create-confirm')).toBeEnabled()
    expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls)).toEqual([])
    expect((await readdir(join(launcher.gameDataPath, 'versions'))).some(id => id.startsWith('mmc-'))).toBe(false)
    await put(baseFile, JSON.stringify({ ...base, assets: 'changed' }))
    await page.getByTestId('instance-create-confirm').click()
    await expect(dialog.getByRole('alert')).toContainText('El origen cambió')
    expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls)).toEqual([])
    await review.click()
    await expect(page.getByTestId('instance-create-confirm')).toBeEnabled()
    const win = await launcher.app.browserWindow(page)
    await win.evaluate(win => win.setContentSize(800, 400))
    await page.getByTestId('instance-create-confirm').focus()
    await expect(page.getByTestId('instance-create-confirm')).toBeInViewport({ ratio: 1 })
    await snap(launcher, `prism-partial-${location}-800`, 'Base Minecraft completada y parches conservados, con confirmación accesible en ventana mínima.')
    await page.getByTestId('instance-create-confirm').click()
    await expect(dialog.getByRole('button', { name: 'Ver instancia', exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Ver instancia', exact: true }).click()
    const destination = await page.evaluate(() => localStorage.getItem('selectedInstancePath'))
    const instance = JSON.parse(await readFile(join(destination!, 'instance.json'), 'utf8'))
    const resolved = await page.evaluate(async id => (window as any).serviceChannels.open('VersionService').call('resolveLocalVersion', id), instance.version)
    expect(resolved.mainClass).toBe('custom.Main')
    expect(resolved.minecraftVersion).toBe('1.7.10')
    expect(resolved.javaVersion.majorVersion).toBe(17)
    expect(resolved.assets).toBe('changed')
    expect(resolved.libraries.map((library: any) => library.name)).toEqual(['qa.base:library:1', 'qa.partial:local:1'])
    expect(resolved.arguments.game).toEqual(['--username', '${auth_player_name}', '--tweakClass', 'custom.Tweaker'])
    expect(resolved.arguments.jvm).toContain('${classpath}')
    expect(resolved.arguments.jvm).toContain('-Dcustom=true')
    expect(await readFile(originalClient, 'utf8')).toBe('keep-official')
    expect(await readFile(join(launcher.gameDataPath, `versions/${resolved.clientJar}/${resolved.clientJar}.jar`), 'utf8')).toBe(client)
    for (const value of ['personal.exe', 'personal.jar', 'never-run']) expect(JSON.stringify(instance)).not.toContain(value)
    expect(await readFile(join(destination!, 'saves/Sentinel/level.dat'), 'utf8')).toBe('source-world')
    await page.reload()
    expect(JSON.parse(await readFile(baseFile, 'utf8')).assets).toBe('changed')
    expect(errors).toEqual([])
  })
