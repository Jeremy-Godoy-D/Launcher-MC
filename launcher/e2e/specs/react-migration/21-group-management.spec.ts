import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import axe from 'axe-core'
import { test, expect, snap } from '../../helpers/scratch'
import { seedReactLibrary } from '../../helpers/react-library'

test.use({ launcherOptions: { locale: 'es-ES' } })
test('group review detects concurrent edits, renames durably and dissolves without removing instances or unknown edition members', async ({ launcher }, testInfo) => {
  const page = launcher.main, paths = await seedReactLibrary(page)
  const storedPaths = paths.map(path => relative(join(launcher.gameDataPath, 'instances'), path))
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await mkdir(join(paths[0], 'saves/Sentinel'), { recursive: true })
  await writeFile(join(paths[0], 'saves/Sentinel/level.dat'), 'keep-group-world')
  await page.evaluate(async paths => {
    const service = (window as any).serviceChannels.open('InstanceService'), state = await service.call('getSharedInstancesState')
    await service.call('updateInstanceGroups', state.groups, [{ id: 'friends', name: 'Amigos QA', color: '#123456', instances: [paths[0], paths[1], 'unknown-edition'] }, { id: 'empty', name: 'Vacío QA', color: '#abcdef', instances: [] }, paths[2]])
  }, paths)
  await page.getByTestId('nav-library').click()
  await page.getByLabel('Filtrar por grupo', { exact: true }).selectOption('id:friends')
  const trigger = page.getByTestId('library-groups'), dialog = page.getByTestId('library-groups-dialog')
  const main = await launcher.app.browserWindow(page), reports: unknown[] = []
  for (const appearance of ['dark', 'light']) {
    await page.getByTestId('nav-settings').click(); await page.getByLabel('Apariencia', { exact: true }).selectOption(appearance)
    await page.getByTestId('nav-library').click(); await trigger.click()
    await expect(page.getByLabel('Nombre del grupo', { exact: true })).toBeVisible()
    for (const width of [1200, 800]) {
      await main.evaluate((win, width) => win.setContentSize(width, width === 800 ? 400 : 720), width)
      await page.getByTestId('group-confirm').focus()
      await expect(page.getByTestId('group-confirm')).toBeInViewport({ ratio: 1 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.evaluate(axe.source)
      const report = await page.evaluate(async () => (window as any).axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } }))
      expect(report.violations).toEqual([]); reports.push({ appearance, width, ...report })
      await snap(launcher, `groups-${appearance}-${width}`, 'Gestión de grupos sin cambiar selección; acciones fijas y contenido desplazable.')
    }
    await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  }
  await writeFile(testInfo.outputPath('groups-accessibility.json'), JSON.stringify(reports, null, 2))
  await page.getByLabel('Filtrar por grupo', { exact: true }).selectOption('id:friends')
  await trigger.click()
  await page.getByLabel('Nombre del grupo', { exact: true }).fill('Vacío QA')
  await page.getByTestId('group-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('todavía no exista')
  await page.getByLabel('Nombre del grupo', { exact: true }).fill('Bosque QA')
  await page.evaluate(async () => {
    const service = (window as any).serviceChannels.open('InstanceService'), state = await service.call('getSharedInstancesState')
    await service.call('updateInstanceGroups', state.groups, state.groups.map((group: any) => typeof group !== 'string' && group.id === 'empty' ? { ...group, name: 'Changed elsewhere QA' } : group))
  })
  await page.getByTestId('group-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('cambiaron en otra ventana')
  await expect(page.getByLabel('Nombre del grupo', { exact: true })).toHaveValue('Bosque QA')
  await dialog.getByRole('button', { name: 'Revisar grupos de nuevo', exact: true }).click()
  await page.getByLabel('Nombre del grupo', { exact: true }).fill('Bosque QA')
  await page.getByTestId('group-confirm').click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  let persisted = JSON.parse(await readFile(join(launcher.appDataPath, 'LauncherMC/instances.json'), 'utf8'))
  expect(persisted.groups[0]).toEqual({ id: 'friends', name: 'Bosque QA', color: '#123456', instances: [storedPaths[0], storedPaths[1], 'unknown-edition'] })
  expect(persisted.groups[1].name).toBe('Changed elsewhere QA')
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  await page.reload()
  await page.getByTestId('nav-library').click()
  await page.getByLabel('Filtrar por grupo', { exact: true }).selectOption({ label: 'Bosque QA' })
  await expect(page.locator('.library-page .instance-card')).toHaveCount(2)
  await trigger.click()
  await dialog.getByRole('checkbox', { name: 'Disolver este grupo', exact: true }).check()
  await expect(page.getByLabel('Nombre del grupo', { exact: true })).toBeDisabled()
  await page.getByTestId('group-confirm').click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Filtrar por grupo', { exact: true })).toHaveValue('')
  await expect(page.locator('.library-page .instance-card')).toHaveCount(3)
  persisted = JSON.parse(await readFile(join(launcher.appDataPath, 'LauncherMC/instances.json'), 'utf8'))
  expect(persisted.groups).toEqual([storedPaths[0], storedPaths[1], 'unknown-edition', { id: 'empty', name: 'Changed elsewhere QA', color: '#abcdef', instances: [] }, storedPaths[2]])
  expect(await readFile(join(paths[0], 'saves/Sentinel/level.dat'), 'utf8')).toBe('keep-group-world')
  expect(await page.evaluate(() => localStorage.getItem('selectedInstancePath'))).toBe(paths[0])
  expect(errors).toEqual([])
})

test('group management is available with an empty library and can remove a legacy empty group without creating instances', async ({ launcher }) => {
  const page = launcher.main
  await page.getByTestId('nav-library').click(); await page.getByTestId('library-groups').click()
  const dialog = page.getByTestId('library-groups-dialog')
  await expect(dialog).toContainText('No hay grupos')
  await expect(page.getByTestId('group-confirm')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.evaluate(async () => {
    const service = (window as any).serviceChannels.open('InstanceService'), state = await service.call('getSharedInstancesState')
    await service.call('updateInstanceGroups', state.groups, [{ id: 'empty', name: 'Legacy empty', color: '', instances: [] }])
  })
  await page.getByTestId('library-groups').click()
  await dialog.getByRole('checkbox', { name: 'Disolver este grupo', exact: true }).check()
  await page.getByTestId('group-confirm').click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  const saved = JSON.parse(await readFile(join(launcher.appDataPath, 'LauncherMC/instances.json'), 'utf8'))
  expect(saved.groups).toEqual([])
  const state = await page.evaluate(async () => (window as any).serviceChannels.open('InstanceService').call('getSharedInstancesState'))
  expect(state.instances).toEqual([])
})
