import { writeFile } from 'node:fs/promises'
import { test, expect, snap } from '../../helpers/scratch'

test('React migrates preferences without reviving themes, persists them and synchronizes windows and runtime locales', async ({ launcher }, testInfo) => {
  const page = launcher.main
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await expect(page.getByTestId('react-prototype')).toBeVisible()
  await page.evaluate(() => {
    localStorage.removeItem('launcher.react.preferences')
    localStorage.setItem('darkTheme', 'light')
    localStorage.setItem('aurora.performanceMode', 'true')
    localStorage.setItem('themes', '{"old":{"customCss":"body { display: none }"}}')
    localStorage.setItem('unrelated-fixture', 'preserve')
  })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.getByTestId('react-prototype')).toHaveAttribute('data-performance', 'true')
  expect(await page.evaluate(() => localStorage.getItem('unrelated-fixture'))).toBe('preserve')
  expect(await page.evaluate(() => localStorage.getItem('themes'))).toContain('display: none')
  await page.getByTestId('nav-settings').click()
  await expect(page.getByLabel('Apariencia', { exact: true })).toHaveValue('light')
  const opening = launcher.app.waitForEvent('window')
  await launcher.app.evaluate(async ({ BrowserWindow, app }) => {
    const win = new BrowserWindow({ width: 800, height: 400, minWidth: 800, minHeight: 400, frame: false, webPreferences: { preload: `${app.getAppPath()}/index-preload.js`, contextIsolation: true, sandbox: true, nodeIntegration: false } })
    await win.loadURL('http://xmcl.runtime/index.html#/setting')
  })
  const other = await opening
  other.on('pageerror', error => errors.push(error.message))
  await expect(other.getByLabel('Apariencia', { exact: true })).toHaveValue('light')
  await page.getByLabel('Apariencia', { exact: true }).selectOption('dark')
  await page.getByRole('checkbox', { name: 'Modo rendimiento' }).uncheck()
  await page.getByRole('checkbox', { name: 'Vídeo ambiental' }).uncheck()
  await page.getByRole('checkbox', { name: 'Presentación automática' }).uncheck()
  await expect(other.getByLabel('Apariencia', { exact: true })).toHaveValue('dark')
  await expect(other.getByRole('checkbox', { name: 'Modo rendimiento' })).not.toBeChecked()
  await expect(other.getByRole('checkbox', { name: 'Vídeo ambiental' })).not.toBeChecked()
  expect(await (await launcher.app.browserWindow(other)).evaluate(win => win.getContentSize())).toEqual([800, 400])
  await other.getByRole('checkbox', { name: 'Modo rendimiento' }).check()
  await expect(page.getByRole('checkbox', { name: 'Modo rendimiento' })).toBeChecked()
  await other.getByRole('checkbox', { name: 'Modo rendimiento' }).uncheck()
  await other.getByRole('button', { name: 'Ver créditos' }).click()
  await expect(other.getByRole('dialog')).toBeVisible()
  await snap({ ...launcher, main: other }, 'preferences-minimum-credits', 'Controles inferiores alcanzables con scroll y diálogo abierto desde ajustes de 800×400.')
  await other.keyboard.press('Escape')
  await page.reload()
  await expect(page.getByLabel('Apariencia', { exact: true })).toHaveValue('dark')
  await expect(page.getByRole('checkbox', { name: 'Presentación automática' })).not.toBeChecked()
  await page.getByLabel('Apariencia', { exact: true }).selectOption('system')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')

  const controlOpening = launcher.app.waitForEvent('window')
  await launcher.app.evaluate(async ({ BrowserWindow, app }) => {
    const win = new BrowserWindow({ show: false, webPreferences: { preload: `${app.getAppPath()}/index-preload.js`, contextIsolation: true, sandbox: true, nodeIntegration: false } })
    await win.loadURL('about:blank')
  })
  const control = await controlOpening
  const setLocale = (locale: string) => control.evaluate(async locale => {
    const state = await (window as any).serviceChannels.open('BaseService').call('getSettings')
    await state.commit('localeSet', locale)
    await state.unref()
  }, locale)
  await setLocale('en')
  await expect(page.getByTestId('nav-home')).toHaveText('Home')
  await expect(other.getByTestId('nav-home')).toHaveText('Home')
  await setLocale('ar')
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await expect(other.locator('html')).toHaveAttribute('lang', 'ar')
  await setLocale('es-ES')
  await expect(page.getByTestId('nav-home')).toHaveText('Inicio')
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr')
  await snap({ ...launcher, main: other }, 'preferences-minimum-synced', 'Preferencias sincronizadas en segunda ventana de 800×400; origen y servicios reales, perfil desechable.')
  expect(errors).toEqual([])
  await writeFile(testInfo.outputPath('preferences-i18n.json'), JSON.stringify({ preferences: await page.evaluate(() => JSON.parse(localStorage.getItem('launcher.react.preferences')!)), legacyPreserved: true, crossWindow: true, runtimeLocales: ['en', 'ar', 'es-ES'], errors }, null, 2), 'utf8')
  await control.close()
  await other.close()
})
