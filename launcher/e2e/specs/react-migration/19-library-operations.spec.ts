import { _electron, type Page } from '@playwright/test'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import axe from 'axe-core'
import { test, expect, snap } from '../../helpers/scratch'
import { seedReactLibrary } from '../../helpers/react-library'
import { waitForAppWindow } from '../../fixtures/launcher'

test.use({ launcherOptions: { locale: 'es-ES' } })
async function options(page: Page, name: string) {
  await page.getByTestId('nav-library').click()
  await page.getByRole('button', { name: `Opciones de ${name}`, exact: true }).click()
  return page.getByTestId('instance-operations')
}
async function createWorld(path: string) { await mkdir(join(path, 'saves/Sentinel'), { recursive: true }); await writeFile(join(path, 'saves/Sentinel/level.dat'), 'world-data') }
test('metadata editing is accessible, detects conflicts, preserves selection and keeps the folder after a full restart', async ({ launcher }, testInfo) => {
  const page = launcher.main, paths = await seedReactLibrary(page)
  await createWorld(paths[0])
  const original = JSON.parse(await readFile(join(paths[0], 'instance.json'), 'utf8'))
  const dialog = await options(page, 'Mi mundo')
  await dialog.getByRole('button', { name: 'Editar datos', exact: true }).click()
  await page.getByLabel('Nombre de la instancia', { exact: true }).fill('Edited QA')
  await page.evaluate(async path => (window as any).serviceChannels.open('InstanceService').call('editInstance', { instancePath: path, description: 'Changed elsewhere' }), paths[0])
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('Los datos cambiaron')
  await page.keyboard.press('Escape')
  const win = await launcher.app.browserWindow(page)
  const reports: unknown[] = []
  for (const appearance of ['dark', 'light']) {
    await page.getByTestId('nav-settings').click()
    await page.getByLabel('Apariencia', { exact: true }).selectOption(appearance)
    await options(page, 'Mi mundo')
    await dialog.getByRole('button', { name: 'Editar datos', exact: true }).click()
    for (const width of [1200, 800]) {
      await win.evaluate((win, width) => win.setContentSize(width, width === 800 ? 400 : 720), width)
      await page.getByTestId('instance-operation-confirm').focus()
      await expect(page.getByTestId('instance-operation-confirm')).toBeInViewport({ ratio: 1 })
      await page.evaluate(axe.source)
      const report = await page.evaluate(async () => (window as any).axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } }))
      expect(report.violations).toEqual([])
      reports.push({ appearance, width, ...report })
      await snap(launcher, `edit-${appearance}-${width}`, 'Edición de metadatos con acciones fijas y cuerpo desplazable; instancia y carpeta capturadas.')
    }
    if (appearance === 'dark') await page.keyboard.press('Escape')
  }
  await writeFile(testInfo.outputPath('operations-accessibility.json'), JSON.stringify(reports, null, 2))
  await page.getByLabel('Nombre de la instancia', { exact: true }).fill('Edited QA')
  await page.getByLabel('Descripción', { exact: true }).fill('Edited description')
  await page.getByLabel('Autor', { exact: true }).fill('QA author')
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  await page.keyboard.press('Escape')
  const saved = JSON.parse(await readFile(join(paths[0], 'instance.json'), 'utf8'))
  expect(saved.name).toBe('Edited QA')
  expect(saved.description).toBe('Edited description')
  expect(saved.author).toBe('QA author')
  expect(saved.runtime).toEqual(original.runtime)
  expect(await page.evaluate(() => localStorage.getItem('selectedInstancePath'))).toBe(paths[0])
  const executablePath = await launcher.app.evaluate(() => process.execPath)
  await launcher.app.close()
  const restarted = await _electron.launch({ executablePath, args: [], env: { ...process.env, XMCL_E2E: '1', XMCL_E2E_APP_DATA: launcher.appDataPath, XMCL_E2E_GAME_DATA: launcher.gameDataPath, XMCL_E2E_NO_LAUNCH: '1', XMCL_E2E_LOCALE: 'es-ES', NODE_ENV: 'production' }, timeout: 60000 })
  try {
    const next = await waitForAppWindow(restarted, /\/(index|setup)\.html(\?|#|$)/, 30000)
    await next.getByTestId('nav-library').click()
    await expect(next.getByRole('button', { name: 'Opciones de Edited QA', exact: true })).toBeVisible()
    expect(await next.evaluate(() => localStorage.getItem('selectedInstancePath'))).toBe(paths[0])
    expect(await readFile(join(paths[0], 'saves/Sentinel/level.dat'), 'utf8')).toBe('world-data')
  } finally { await restarted.close() }
})
test('copying and removal capture the target, preserve original worlds and block managed hidden-folder conflicts', async ({ launcher }) => {
  const page = launcher.main, paths = await seedReactLibrary(page)
  await createWorld(paths[0])
  const dialog = await options(page, 'Mi mundo')
  await dialog.getByRole('button', { name: 'Duplicar', exact: true }).click()
  await page.getByTestId('instance-operation-confirm').click({ clickCount: 2 })
  await expect(dialog).toHaveCount(0)
  const duplicate = await page.evaluate(() => localStorage.getItem('selectedInstancePath'))
  expect(duplicate).not.toBe(paths[0])
  expect(await readFile(join(duplicate!, 'saves/Sentinel/level.dat'), 'utf8')).toBe('world-data')
  await writeFile(join(duplicate!, 'saves/Sentinel/level.dat'), 'copy-only')
  expect(await readFile(join(paths[0], 'saves/Sentinel/level.dat'), 'utf8')).toBe('world-data')
  const copied = JSON.parse(await readFile(join(duplicate!, 'instance.json'), 'utf8'))
  await options(page, copied.name)
  await dialog.getByRole('button', { name: 'Retirar o eliminar', exact: true }).click()
  const hidden = join(dirname(duplicate!), `.${duplicate!.split(/[\\/]/).at(-1)}`)
  await mkdir(hidden)
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('No se completó')
  await page.keyboard.press('Escape')
  await options(page, 'Mi mundo')
  await dialog.getByRole('button', { name: 'Retirar o eliminar', exact: true }).click()
  await dialog.getByRole('checkbox').check()
  await expect(page.getByTestId('instance-operation-confirm')).toBeDisabled()
  await page.getByLabel('Escribe «Mi mundo» para confirmar el borrado', { exact: true }).fill('Mi mundo')
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog).toHaveCount(0)
  expect(await readFile(join(launcher.gameDataPath, 'saves/Sentinel/level.dat'), 'utf8')).toBe('world-data')
  expect(await readFile(join(duplicate!, 'saves/Sentinel/level.dat'), 'utf8')).toBe('copy-only')
  await options(page, 'Fabric QA')
  await dialog.getByRole('button', { name: 'Retirar o eliminar', exact: true }).click()
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog).toHaveCount(0)
  expect((await readdir(dirname(paths[1]))).some(name => name === '.Fabric QA')).toBe(true)
  await expect(page.getByRole('button', { name: `Opciones de ${copied.name}`, exact: true })).toBeVisible()
})
test('groups and manual ordering persist, preserve hidden edition data and support keyboard context actions', async ({ launcher }) => {
  const page = launcher.main, paths = await seedReactLibrary(page)
  const previous = await page.evaluate(async () => (window as any).serviceChannels.open('InstanceService').call('getSharedInstancesState'))
  await page.evaluate(async ({ previous, path }) => {
    await (window as any).serviceChannels.open('InstanceService').call('updateInstanceGroups', previous.groups, [{ id: 'old', name: 'Legacy', color: '#123456', instances: ['unknown-edition'] }, path])
  }, { previous, path: paths[0] })
  await page.getByTestId('nav-library').click()
  const trigger = page.getByRole('button', { name: 'Opciones de Mi mundo', exact: true })
  await trigger.focus(); await trigger.press('Shift+F10')
  const dialog = page.getByTestId('instance-operations')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Grupo', exact: true }).click()
  await page.getByLabel('Grupo', { exact: true }).selectOption('new')
  await page.getByLabel('Nombre del grupo', { exact: true }).fill('Friends QA')
  await page.getByTestId('instance-operation-confirm').click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.getByLabel('Filtrar por grupo', { exact: true }).selectOption({ label: 'Friends QA' })
  await expect(page.locator('.library-page .instance-card')).toHaveCount(1)
  await page.getByLabel('Filtrar por grupo', { exact: true }).selectOption('')
  await page.getByLabel('Ordenar instancias', { exact: true }).selectOption('name')
  expect(await page.locator('.library-page h3').allTextContents()).toEqual(['Bajo la superficie', 'Fabric QA', 'Mi mundo'])
  await page.reload()
  await expect(page.getByLabel('Ordenar instancias', { exact: true })).toHaveValue('name')
  await options(page, 'Fabric QA')
  await dialog.getByRole('button', { name: 'Subir en orden manual', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('Cambios guardados.')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Ordenar instancias', { exact: true })).toHaveValue('manual')
  const persisted = JSON.parse(await readFile(join(launcher.appDataPath, 'LauncherMC/instances.json'), 'utf8'))
  expect(persisted.groups[0]).toMatchObject({ name: 'Legacy', color: '#123456', instances: ['unknown-edition'] })
  expect(persisted.groups.some((group: any) => typeof group !== 'string' && group.name === 'Friends QA')).toBe(true)
})
