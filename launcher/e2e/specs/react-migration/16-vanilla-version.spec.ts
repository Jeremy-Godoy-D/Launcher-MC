import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import axe from 'axe-core'
import { test, expect, snap } from '../../helpers/scratch'
import { mockCreationMetadata } from '../../helpers/react-creation'
import { stubOpenDialog } from '../../helpers/tasks/importModpack'

test.use({ launcherOptions: { locale: 'es-ES' } })

test('Vanilla local version review preserves inheritance, client, libraries and world without adopting personal launcher settings', async ({ launcher }, testInfo) => {
  const page = launcher.main
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await mockCreationMetadata(launcher)
  const source = join(launcher.gameDataPath, 'vanilla-source'), game = join(launcher.gameDataPath, 'separate-game')
  async function file(path: string, data: string) { const target = join(source, path); await mkdir(dirname(target), { recursive: true }); await writeFile(target, data) }
  const sha1 = (value: string) => createHash('sha1').update(value).digest('hex')
  await file('launcher_profiles.json', JSON.stringify({ profiles: { qa: { name: 'Vanilla custom QA', lastVersionId: 'custom', gameDir: game, javaDir: 'untrusted.exe', javaArgs: '-javaagent:personal.jar' } } }))
  await file('versions/1.21.1/1.21.1.json', JSON.stringify({ id: '1.21.1', mainClass: 'net.minecraft.client.main.Main', minecraftArguments: '--username ${auth_player_name}', javaVersion: { component: 'java-runtime-delta', majorVersion: 21 }, downloads: { client: { sha1: sha1('fixture-client'), size: 14, url: 'https://example.com/client.jar' } }, libraries: [{ name: 'qa.vanilla:local:1', downloads: { artifact: { sha1: sha1('fixture-library'), size: 15, path: 'qa/vanilla/local/1/local-1.jar', url: 'https://example.com/library.jar' } } }] }))
  const custom = (mainClass: string) => JSON.stringify({ id: 'custom', inheritsFrom: '1.21.1', mainClass, libraries: [], preExecuteCommand: 'never-run', java: 'untrusted.exe' })
  await file('versions/custom/custom.json', custom('custom.Main'))
  await file('versions/1.21.1/1.21.1.jar', 'fixture-client')
  await file('libraries/qa/vanilla/local/1/local-1.jar', 'fixture-library')
  await mkdir(join(game, 'saves/Sentinel'), { recursive: true })
  await writeFile(join(game, 'saves/Sentinel/level.dat'), 'source-world')
  await writeFile(join(game, 'launcher_accounts.json'), 'not imported')
  await page.getByTestId('nav-library').click()
  const open = async () => {
    await page.getByTestId('library-create-instance').click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Importar modpack', exact: true }).click()
    await dialog.getByRole('button', { name: 'Carpeta existente', exact: true }).click()
    await page.getByLabel('Formato de la carpeta', { exact: true }).selectOption('vanilla')
    await stubOpenDialog(launcher, source)
    await dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true }).click()
    await expect(dialog).toContainText('Versión local de Minecraft revisada')
    await expect(dialog.getByRole('status')).toContainText('Minecraft 1.21.1')
    return dialog
  }
  const dialog = await open()
  expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls)).toEqual([])
  expect((await readdir(join(launcher.gameDataPath, 'versions')).catch(() => [])).filter(id => id.startsWith('vanilla-'))).toEqual([])
  await file('versions/custom/custom.json', custom('changed.Main'))
  await page.getByTestId('instance-create-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('El origen cambió')
  expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls)).toEqual([])
  await dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true }).click()
  await expect(dialog).toContainText('Versión local de Minecraft revisada')
  const win = await launcher.app.browserWindow(page)
  await page.evaluate(axe.source)
  const reports: unknown[] = []
  for (const appearance of ['dark', 'light']) {
    await page.keyboard.press('Escape')
    await page.getByTestId('nav-settings').click()
    await page.getByLabel('Apariencia', { exact: true }).selectOption(appearance)
    await page.getByTestId('nav-library').click()
    await open()
    for (const width of [1200, 800]) {
      await win.evaluate((win, width) => win.setContentSize(width, width === 800 ? 400 : 720), width)
      await page.getByTestId('instance-create-confirm').focus()
      await dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true }).focus()
      await expect(dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true })).toBeInViewport({ ratio: 1 })
      await dialog.getByText('Versión local de Minecraft revisada.', { exact: false }).scrollIntoViewIfNeeded()
      await expect(page.getByTestId('instance-create-confirm')).toBeInViewport({ ratio: 1 })
      const report = await page.evaluate(async () => (window as any).axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } }))
      expect(report.violations).toEqual([])
      reports.push({ appearance, width, ...report })
      await snap(launcher, `vanilla-${appearance}-${width}`, 'Versión Vanilla heredada y cacheada, sin escribir durante revisión; raíz de versiones separada de la carpeta del mundo.')
    }
  }
  await writeFile(testInfo.outputPath('vanilla-accessibility.json'), JSON.stringify(reports, null, 2))
  await page.getByTestId('instance-create-confirm').click()
  await expect(dialog.getByRole('button', { name: 'Ver instancia', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Ver instancia', exact: true }).click()
  const destination = await page.evaluate(() => localStorage.getItem('selectedInstancePath'))
  const saved = JSON.parse(await readFile(join(destination!, 'instance.json'), 'utf8'))
  expect(saved.version).toMatch(/^vanilla-custom-[a-f0-9]{16}$/)
  expect(saved.runtime.minecraft).toBe('1.21.1')
  for (const marker of ['untrusted.exe', 'personal.jar', 'never-run']) expect(JSON.stringify(saved)).not.toContain(marker)
  const definition = await readFile(join(launcher.gameDataPath, 'versions', saved.version, `${saved.version}.json`), 'utf8')
  expect(definition).not.toContain('never-run')
  const resolved = await page.evaluate(async version => (window as any).serviceChannels.open('VersionService').call('resolveLocalVersion', version), saved.version)
  expect(resolved.mainClass).toBe('changed.Main')
  expect(resolved.minecraftVersion).toBe('1.21.1')
  expect(resolved.javaVersion.majorVersion).toBe(21)
  expect(resolved.inheritances).toHaveLength(2)
  expect(await readFile(join(launcher.gameDataPath, 'versions/1.21.1/1.21.1.jar'), 'utf8')).toBe('fixture-client')
  const library = join(launcher.gameDataPath, 'libraries/qa/vanilla/local/1/local-1.jar')
  expect(await readFile(library, 'utf8')).toBe('fixture-library')
  expect(await readdir(destination!)).not.toContain('launcher_accounts.json')
  await writeFile(join(destination!, 'saves/Sentinel/level.dat'), 'changed-copy')
  expect(await readFile(join(game, 'saves/Sentinel/level.dat'), 'utf8')).toBe('source-world')
  await page.reload()
  expect(JSON.parse(await readFile(join(destination!, 'instance.json'), 'utf8')).version).toBe(saved.version)
  await writeFile(library, 'existing-conflict')
  await page.getByTestId('nav-library').click()
  await open()
  await page.getByTestId('instance-name').fill('Conflict copy QA')
  await page.getByTestId('instance-create-confirm').click()
  await expect(dialog.getByRole('alert')).toContainText('contenido distinto')
  expect(await readFile(library, 'utf8')).toBe('existing-conflict')
  expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls.length)).toBe(1)
  expect(errors).toEqual([])
})

test('Vanilla latest release and snapshot resolve to explicit versions; provider errors and unknown uncached custom versions stay blocked', async ({ launcher }) => {
  const page = launcher.main
  await mockCreationMetadata(launcher)
  const source = join(launcher.gameDataPath, 'vanilla-aliases')
  await mkdir(source)
  await writeFile(join(source, 'launcher_profiles.json'), JSON.stringify({ profiles: { release: { name: 'Latest release QA', lastVersionId: 'latest-release' }, snapshot: { name: 'Latest snapshot QA', lastVersionId: 'latest-snapshot' }, missing: { name: 'Missing custom QA', lastVersionId: 'unknown-custom-version' } } }))
  await launcher.app.evaluate(({ ipcMain }) => {
    const original = (ipcMain as any)._invokeHandlers.get('service-call')
    ipcMain.removeHandler('service-call')
    ipcMain.handle('service-call', (event, service, method, ...args) => {
      if (service === 'VersionMetadataService' && method === 'getMinecraftVersions' && (globalThis as any).__failLatest) { (globalThis as any).__failLatest = false; throw new Error('Fixture metadata offline') }
      return original(event, service, method, ...args)
    })
  })
  await page.getByTestId('nav-library').click()
  await page.getByTestId('library-create-instance').click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Importar modpack', exact: true }).click()
  await dialog.getByRole('button', { name: 'Carpeta existente', exact: true }).click()
  await stubOpenDialog(launcher, source)
  await dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Minecraft 1.21.1')
  await launcher.app.evaluate(() => { (globalThis as any).__failLatest = true })
  await page.getByLabel('Perfil que se importará', { exact: true }).selectOption('1')
  await expect(dialog.getByRole('alert')).toContainText('No se pudo revisar')
  await expect(page.getByTestId('instance-create-confirm')).toBeDisabled()
  await page.getByLabel('Perfil que se importará', { exact: true }).selectOption('0')
  await expect(dialog.getByRole('status')).toContainText('Minecraft 1.21.1')
  await page.getByLabel('Perfil que se importará', { exact: true }).selectOption('1')
  await expect(dialog.getByRole('status')).toContainText('Minecraft 24w33a')
  await page.getByTestId('instance-create-confirm').click()
  await expect(dialog.getByRole('button', { name: 'Ver instancia', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Ver instancia', exact: true }).click()
  const path = await page.evaluate(() => localStorage.getItem('selectedInstancePath'))
  expect(JSON.parse(await readFile(join(path!, 'instance.json'), 'utf8')).runtime.minecraft).toBe('24w33a')
  await page.getByTestId('nav-library').click()
  await page.getByTestId('library-create-instance').click()
  await dialog.getByRole('button', { name: 'Importar modpack', exact: true }).click()
  await dialog.getByRole('button', { name: 'Carpeta existente', exact: true }).click()
  await dialog.getByRole('button', { name: 'Elegir carpeta de origen', exact: true }).click()
  await page.getByLabel('Perfil que se importará', { exact: true }).selectOption('2')
  await expect(dialog.getByRole('alert')).toContainText('No se pudo revisar')
  await expect(page.getByTestId('instance-create-confirm')).toBeDisabled()
  expect(await launcher.app.evaluate(() => (globalThis as any).__creationCalls.length)).toBe(1)
})
